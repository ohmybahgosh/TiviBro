#!/usr/bin/env node
/* Writes app/css/nogap.css: margin-based spacing for every flex rule in app/css/app.css that uses
   "gap", for TVs older than webOS 22 (Chromium < 84) where flexbox gap does nothing.
   app/js/compat.js adds class "nogap" to <html> only on those TVs, so newer TVs ignore this file.
     node scripts/gen-nogap.js           write the file
     node scripts/gen-nogap.js --check   exit 1 if the file is out of date (used by npm test) */
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'app', 'css', 'app.css'), OUT = path.join(ROOT, 'app', 'css', 'nogap.css');

function build(css) {
  css = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const out = [];
  const re = /([^{}@]+)\{([^{}]*)\}/g;
  let m;
  while ((m = re.exec(css))) {
    const decl = {};
    m[2].split(';').forEach(d => { const i = d.indexOf(':'); if (i > 0) decl[d.slice(0, i).trim()] = d.slice(i + 1).trim(); });
    if (!/flex/.test(decl.display || '') || !(decl.gap || decl['row-gap'] || decl['column-gap'])) continue;
    const parts = (decl.gap || '').split(/\s+/).filter(Boolean);
    const row = decl['row-gap'] || parts[0] || '0', col = decl['column-gap'] || parts[1] || parts[0] || '0';
    const column = /column/.test(decl['flex-direction'] || ''), wrap = /^wrap/.test(decl['flex-wrap'] || '');
    const sels = m[1].split(',').map(s => s.trim()).filter(Boolean);
    const each = (suffix, body) => out.push(sels.map(s => '.nogap ' + s + suffix).join(',') + '{' + body + '}');
    if (wrap) { each(' > *', 'margin-right:' + col + ';margin-bottom:' + row); each('', 'margin-bottom:-' + row); }
    else if (column) each(' > * + *', 'margin-top:' + row);
    else each(' > * + *', 'margin-left:' + col);
  }
  return '/* Generated by scripts/gen-nogap.js from app.css: flex "gap" for TVs older than webOS 22.  Do not edit. */\n' + out.join('\n') + '\n';
}

const want = build(fs.readFileSync(SRC, 'utf8'));
if (process.argv.includes('--check')) {
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (have !== want) { console.error('FAIL app/css/nogap.css is out of date: run node scripts/gen-nogap.js'); process.exit(1); }
  console.log('nogap.css is up to date (' + (want.split('\n').length - 2) + ' rules)');
} else {
  fs.writeFileSync(OUT, want);
  console.log('wrote app/css/nogap.css (' + (want.split('\n').length - 2) + ' rules)');
}
