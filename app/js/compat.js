/* Small fixes for older webOS browsers, loaded before everything else.
   webOS TV 25 (Chromium 120) needs none of this; it keeps 4.x (Chromium 53), 5.x (68), 6.x (79)
   and 22 (87) working with the same code.  Keep it tiny and dependency-free: plain ES5.
     - Promise.prototype.finally (Chromium 63)
     - Object.entries / Object.values (Chromium 54) and String padStart / padEnd (Chromium 57):
       the bundled players use them (hls.js, and mpegts.js when it reads an HEVC stream)
     - Flexbox "gap" (Chromium 84): when missing, <html> gets class "nogap" and css/nogap.css
       spaces flex children with margins instead (that file is generated by scripts/gen-nogap.js).
   It also makes sure a TV never just shows a black screen: on webOS 3 and older (no modern
   JavaScript) it says the TV is too old, and if the app fails to start it shows why. */
(function () {
  'use strict';
  if (!Object.entries) Object.entries = function (o) { var k = Object.keys(o), r = []; for (var i = 0; i < k.length; i++) r.push([k[i], o[k[i]]]); return r; };
  if (!Object.values) Object.values = function (o) { var k = Object.keys(o), r = []; for (var i = 0; i < k.length; i++) r.push(o[k[i]]); return r; };
  function pad(s, len, fill, start) {
    s = String(s); len = len >> 0; fill = fill === undefined ? ' ' : String(fill);
    if (s.length >= len || !fill) return s;
    var need = len - s.length, p = '';
    while (p.length < need) p += fill;
    p = p.slice(0, need);
    return start ? p + s : s + p;
  }
  if (!String.prototype.padStart) String.prototype.padStart = function (len, fill) { return pad(this, len, fill, true); };
  if (!String.prototype.padEnd) String.prototype.padEnd = function (len, fill) { return pad(this, len, fill, false); };
  if (typeof Promise !== 'undefined' && !Promise.prototype.finally) {
    Promise.prototype.finally = function (fn) {
      var P = this.constructor || Promise;
      return this.then(
        function (v) { return P.resolve(fn()).then(function () { return v; }); },
        function (e) { return P.resolve(fn()).then(function () { throw e; }); });
    };
  }

  // Flex gap test: two 1px-tall items in a column with a 1px row gap measure 3px only if gap works.
  function flexGap() {
    var root = document.documentElement, d = document.createElement('div');
    d.style.cssText = 'display:flex;flex-direction:column;row-gap:1px;position:absolute;visibility:hidden';
    d.appendChild(document.createElement('div')).style.height = '1px';
    d.appendChild(document.createElement('div')).style.height = '1px';
    root.appendChild(d);
    var ok = d.scrollHeight === 3;
    root.removeChild(d);
    return ok;
  }
  try { if (!flexGap()) document.documentElement.className += ' nogap'; } catch (e) {}

  /* ---------- never a black screen ---------- */
  var modern = true;
  try { new Function('"use strict"; let a = 1; const f = (x) => x + a; class K {} return `${f(1)}`;')(); } catch (e) { modern = false; }
  var errors = [];
  window.addEventListener('error', function (e) { if (errors.length < 5) errors.push((e.message || 'error') + (e.filename ? '  (' + String(e.filename).split('/').pop() + ':' + e.lineno + ')' : '')); });
  window.addEventListener('unhandledrejection', function (e) { var r = e && e.reason; if (errors.length < 5) errors.push(String(r && r.message || r || 'error') + (r && r.stack ? '  (' + String(r.stack).split('\n')[1].replace(/^\s+at\s+/, '').split('/').pop() + ')' : '')); });
  function screen(title, lines, retry) {
    var b = document.body; if (!b) return;
    var box = document.createElement('div');
    box.style.cssText = 'position:fixed;left:0;top:0;right:0;bottom:0;z-index:999;background:#0b0e1a;color:#e8ecf8;font-family:sans-serif;padding:140px 160px;font-size:30px;line-height:1.5';
    var h = document.createElement('div'); h.style.cssText = 'font-size:52px;font-weight:bold;margin-bottom:30px'; h.textContent = title; box.appendChild(h);
    for (var i = 0; i < lines.length; i++) { var p = document.createElement('div'); p.style.cssText = i && lines[i].charAt(0) === ' ' ? 'font-size:22px;color:#8f9bbf' : 'margin-bottom:18px'; p.textContent = lines[i]; box.appendChild(p); }
    b.appendChild(box);
    if (retry) document.addEventListener('keydown', function (e) { if (e.keyCode === 13) location.reload(); }, true);
  }
  window.addEventListener('load', function () {
    if (!modern) return screen('This TV is too old for TiviBro', ['TiviBro needs webOS 4 or newer, which LG TVs have from 2018.  This TV\'s web browser cannot run it.']);
    var fail = function (extra) {
      screen('TiviBro could not start', ['Press OK to try again.  If it keeps happening, reinstall TiviBro and send the details below with your report.']
        .concat(extra || []).concat(errors.map(function (x) { return '  ' + x; })).concat(['  ' + navigator.userAgent]), true);
    };
    // A file that failed to load leaves its part of the app missing: certain, so say so at once.
    var parts = ['U', 'Log', 'Store', 'Library', 'Epg', 'Caps', 'Player', 'UI', 'Views', 'Guide', 'Settings', 'App'], missing = [];
    for (var i = 0; i < parts.length; i++) if (typeof window[parts[i]] === 'undefined') missing.push(parts[i]);
    if (missing.length) return setTimeout(function () { fail(['  Missing: ' + missing.join(', ')]); }, 300);
    // Errors while starting: only if the app still isn't up a while later (a slow first download is fine).
    // The app sets __tbBooted once the channels or the setup screen are showing.
    var t0 = Date.now(), check = setInterval(function () {
      if (window.__tbBooted) return clearInterval(check);
      if (errors.length && Date.now() - t0 > 8000) { clearInterval(check); fail(); }
      if (Date.now() - t0 > 120000) clearInterval(check);
    }, 1000);
  });
})();
