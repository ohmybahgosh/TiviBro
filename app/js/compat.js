/* Small fixes for older webOS browsers, loaded before everything else.
   webOS TV 25 (Chromium 120) needs none of this; it keeps 4.x (Chromium 53), 5.x (68), 6.x (79)
   and 22 (87) working with the same code.  Keep it tiny and dependency-free: plain ES5.
     - Promise.prototype.finally (Chromium 63)
     - Flexbox "gap" (Chromium 84): when missing, <html> gets class "nogap" and css/nogap.css
       spaces flex children with margins instead (that file is generated by scripts/gen-nogap.js). */
(function () {
  'use strict';
  if (typeof Promise !== 'undefined' && !Promise.prototype.finally) {
    Promise.prototype.finally = function (fn) {
      var P = this.constructor || Promise;
      return this.then(
        function (v) { return P.resolve(fn()).then(function () { return v; }); },
        function (e) { return P.resolve(fn()).then(function () { throw e; }); });
    };
  }

  // Flex gap test: two 1px-tall items in a column with a 1px row gap measure 3px only if gap works.
  function flexGap() {
    var root = document.documentElement, d = document.createElement('div');
    d.style.cssText = 'display:flex;flex-direction:column;row-gap:1px;position:absolute;visibility:hidden';
    d.appendChild(document.createElement('div')).style.height = '1px';
    d.appendChild(document.createElement('div')).style.height = '1px';
    root.appendChild(d);
    var ok = d.scrollHeight === 3;
    root.removeChild(d);
    return ok;
  }
  try { if (!flexGap()) document.documentElement.className += ' nogap'; } catch (e) {}
})();
